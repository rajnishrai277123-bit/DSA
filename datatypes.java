public class datatypes {
    public static void main(String[]args){
        byte b=8;
        System.out.println("The value of byte b is: " + b);
        char ch='a';
        System.out.println("The value of char ch is: " + ch);
        boolean var=true;
        System.out.println("The value of boolean var is: " + var);
        float price=10.5f;
        System.out.println("The value of float price is: " + price);
        short sh=5;
        System.out.println("The value of short sh is: " + sh);
    }
}